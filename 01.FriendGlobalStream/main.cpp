#include <iostream>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                   Глобальні та дружні функції-оператори, перевантаження << і >>, дружні класи
==========================================================================================================================================

  Перевантаження оператора методом-членом класу не завжди достатньо, тому що лівий операнд - завжди об'єкт, іноді ж нам необхідно, щоб
  лівий операнд був простим типом (char, bool, int, double).  Для таких випадків оператор оголошують функцією ПОЗА класом.

                                                          Глобальна функція-оператор
  Глобальна функція-оператор — це функція перевантаження оператора, яка оголошується поза межами класу. Ця функція не член класу - тому
  має доступ  лише до public-членів (гетери, публічні методи). В таку функцію усі операнди передаються параметрами (бінарний оператор - 2
  параметри, унарний - 1): Money operator*(int count, const Money& price);

                                                                Дружня функція
  Дружня функція (friend) — це функція, яка не є методом класу, але має повний доступ до всіх його закритих (private) та захищених
  (protected) елементів (полів та методів). Вона оголошується всередині тіла класу за допомогою ключового слова friend, але її фактичне
  визначення (код) пишеться окремо, як для звичайної глобальної функції.

  * Таким чином клас сам оголошує її своїм другом усередині свого тіла за допомогою ключового слова friend:
  friend ostream& operator<<(ostream& out, const Money& m);

  Відмінності дружньої функції від методу:
  - не має this: об'єкт передається параметром;
  - викликається без об'єкта і крапки;
  - секція (public чи private), у якій написано friend, не має значення;
  - дружбу надає лише сам клас: «оголосити себе другом» ззовні класу неможливо.

                                           Перевантаження введення-виведення (перевантаження << і >>)
  Ми вміємо створювати свій метод print() для виводу полів класу, але що якщо ми хочемо працювати саме з об'єктом в cout та cin у тому
  стилі як вони пропонують?

  cout — об'єкт класу ostream (потік виведення - ostream), cin — об'єкт класу istream (потік введення - istream). Це накладає на нас
  певні обмеження:
  1.  Лівий операнд стає об'єктом класу потоку введення-виведення (stream class) - точніше посиланням на екземпляр класу стандартної
  бібліотеки введення-виведення (ostream/istream), який відповідає за послідовну обробку даних.
  2.  Класи введення-виведення (ostream/istream) змінити неможливо.
  3.  Тому перевантаження операторів << і >> можливо лише через глобальну або дружню функцію:
 
  * Пояснення:
  ostream& operator<<(ostream& out, const Money& m)    { out << ...;  return out; }
  istream& operator>>(istream& in, Money& m)           { in >> ...;   return in;  }
  - потік передається і повертається за посиланням: потік не можна копіювати;
  - у << об'єкт передається як const Money& (лише читаємо), у >> — як Money& (змінюємо);
  - оператор повертає посилання на лівий операнд, тому працює ланцюжковий виклик з тим самим об'єктом.

                                                             Дружній клас
  За допомогою ключового слова friend можна також оголосити інший клас дружнім.

  Дружній клас (friend class) — це клас, якому інший клас надає повний доступ до своїх закритих (private) і захищених (protected) членів:
  усі методи дружнього класу можуть звертатися до них напряму.

  В цьому випадку дружба одностороння: тільки дружній клас отримує доступ до полів класу, у якому його оголошено дружнім за допомогою friend.

  friend class Cashier;     // усі методи Cashier мають доступ до private-членів Money
  * Дружба одностороння (Money не отримує доступу до Cashier) і не передається (друг мого друга — не мій друг).
*/

class Money
{
private:
    int amount;             // уся сума в копійках: 12 грн 50 коп → 1250

public:
    Money(int hryvnias, int kopecks) : amount(hryvnias * 100 + kopecks)
    {}

    // Метод-член: price * 3 — лівий операнд Money
    Money operator*(int count) const
    {
        return Money(0, amount * count);
    }

    // Дружні функції: оголошення всередині класу, тіло — за межами класу
    friend ostream& operator<<(ostream& out, const Money& m);
    friend istream& operator>>(istream& in, Money& m);

    // Дружній клас: усі його методи бачать private-члени Money
    friend class Cashier;
};

// Глобальна функція: 3 * price — лівий операнд int, тому метод-член неможливий.
// Доступу до private немає, тому використовуємо публічний метод-член: 3 * price = price * 3
Money operator*(int count, const Money& price)
{
    return price * count;
}

// Дружня функція: перед іменем НЕМАЄ Money:: — це не метод.
// Доступ до private-поля m.amount дозволено, бо Money оголосив цю функцію другом
ostream& operator<<(ostream& out, const Money& m)
{
    int total = m.amount;
    if (total < 0)
    {
        out << "-";
        total = -total;
    }
    out << total / 100 << " грн " << total % 100 << " коп";
    return out;                         // повертаємо потік — для ланцюжка cout << a << b
}

// Читаємо два числа: гривні й копійки
istream& operator>>(istream& in, Money& m)
{
    int hryvnias = 0;
    int kopecks = 0;
    in >> hryvnias >> kopecks;
    m.amount = hryvnias * 100 + kopecks;
    return in;
}

class Cashier
{
public:
    // Ціна зі знижкою у відсотках. Прямий доступ до price.amount — завдяки дружбі
    static Money applyDiscount(const Money& price, int percent)
    {
        return Money(0, price.amount - price.amount * percent / 100);
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    Money price(12, 50);

    cout << "1. Виведення через перевантажений <<" << endl;
    cout << "  ціна: " << price << endl;            // operator<<(cout, price), далі ланцюжок продовжується

    cout << "2. Метод-член і глобальна функція" << endl;
    cout << "  price * 3 = " << price * 3 << endl;  // price.operator*(3)
    cout << "  3 * price = " << 3 * price << endl;  // operator*(3, price)

    cout << "3. Дружній клас" << endl;
    cout << "  зі знижкою 20%: " << Cashier::applyDiscount(price, 20) << endl;

    cout << "4. Введення через перевантажений >>" << endl;
    Money input(0, 0);
    cout << "  Введіть суму (гривні і копійки через пробіл): ";
    cin >> input;                                   // operator>>(cin, input)
    cout << "  Ви ввели: " << input << endl;
    cout << "  Вартість двох таких товарів: " << 2 * input << endl;

    return 0;
}

